// dsh-composer-predict — browser half (client bundle body).
//
// Rendered into the resident composer card through the session-scoped
// `conversation.input.overlay` slot, plus its own Settings navigation entry via
// the root `settings.section` list (the same slot that hosts "Built-in
// plugins"). The composer itself stays owned by dsh: we only read the draft
// through `useInput`, write an accepted suggestion through
// `inputActions.setDraft`, and paint ghost text in an absolutely positioned
// layer over the empty input.
//
// Contract (deliberately the same one OpenCode #54197 establishes):
//   * an offer is only shown for the current session while it is idle and the
//     normal composer is empty;
//   * Tab inserts the whole suggestion into the draft without sending;
//   * Escape dismisses it;
//   * typing, sending, switching session or disabling the feature discards it;
//   * a stale response can never replace or resurrect a newer offer;
//   * suggestions never enter drafts or history until accepted.
//
// The bundle wrapper is generated by scripts/build-client.mjs, which strips the
// import below and the `export` keywords before wrapping this file in the
// dsh ModuleLoader factory.

import { DEFAULT_CONFIG, NS, CHANNEL, ROUTE, clampNumber, extractTail, lastAssistantSeq } from './shared.js'

export const inject = ['slots', 'locale', 'connection']

const EMPTY_NODES = []

/** Wrap a `{ error }` result into the human line the settings card shows. */
const errorText = (result) => {
	const message = result?.error?.message
	return typeof message === 'string' && message !== '' ? message : 'request failed'
}

