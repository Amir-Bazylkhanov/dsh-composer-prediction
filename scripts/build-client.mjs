// Bundle lib/client-body.js (+ the pure helpers from lib/shared.js) into the
// dsh ModuleLoader wrapper the host serves to the browser.
//
// No bundler, no dependencies: both sources are plain JavaScript, so a
// deterministic text transform is enough. The wrapper shape is the one dsh's
// ModuleLoader expects, identical to what the tsdown config of a TypeScript
// plugin emits:
//
//   window.__ModuleLoader__.load({ id, factory: (require) => module.exports })

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ID = 'dsh-composer-prediction'

/** Drop module syntax: shared.js and client-body.js are concatenated into one scope. */
function toScript(source, file) {
	const withoutImports = source.replace(/^[ \t]*import\s[^\n]*\n/gm, '')
	const withoutExports = withoutImports.replace(/^[ \t]*export\s+/gm, '')
	const leftover = withoutExports.match(/^[ \t]*(?:import|export)\s/m)
	if (leftover !== null) throw new Error(`${file}: unsupported module syntax left after transform`)
	return withoutExports.trim()
}

const shared = toScript(readFileSync(join(root, 'lib/shared.js'), 'utf8'), 'lib/shared.js')
const body = toScript(readFileSync(join(root, 'lib/client-body.js'), 'utf8'), 'lib/client-body.js')

const bundle = `// GENERATED by scripts/build-client.mjs — edit lib/client-body.js or lib/shared.js instead.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		var react = require("react");

${shared}

${body}

		var client = createClient(react);
		module.exports = { inject: inject, apply: client.apply };
		return module.exports;
	},
});
`

const out = join(root, 'lib/client.js')
writeFileSync(out, bundle, 'utf8')
process.stdout.write(`wrote ${out} (${bundle.length} bytes)\n`)
